/*
 * REQ_GRSPW_072: DMACTRL reads 0 after clearing its status
 *
 * @tc     TC_GRSPW_009
 * @side   guest
 * @cores  0 1 2 3
 * @peer   none
 */

#include "req_guest.h"

static void test(void)
{
  setup();
  write_chn(CHN_PS | CHN_PR | CHN_TA | CHN_RA);
  check(regs->chn == 0, "DMACTRL reads 0 after a write of PS, PR, TA and RA");
}
