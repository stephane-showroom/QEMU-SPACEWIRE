/*
 * REQ_GRSPW_003: configuration of the RMAP and non-RMAP cores
 *
 * @tc     TC_GRSPW_003
 * @side   guest
 * @cores  0 1 2 3
 * @peer   none
 */

#include "req_guest.h"

static void test(void)
{
  regs->ctr = CTR_RS;
  check((regs->ctr & CTR_CAPABILITIES) == (IS_RMAP_CORE ? CTR_CAPABILITIES : 0),
        "RA, RX and RC set on the RMAP cores only");
}
